/**
 * Tokenizes text and filters stopwords while strictly preserving numbers and protected short tech terms.
 */
export function tokenizeFiltered(text: string): string[] {
  if (!text) return []
  // Matches unicode letters, numbers, and technical identifiers like c++, c#, .net, node.js, 99.99%
  const rawTokens = text.toLowerCase().match(/[\p{L}\p{N}+#.%-]+/gu) || []
  const result: string[] = []

  for (const raw of rawTokens) {
    const token = raw.trim()
    if (!token) continue

    // Protected tech terms are always kept
    if (PROTECTED_TECH_TERMS.has(token)) {
      result.push(token)
      continue
    }

    // Keep numbers and metrics like 10, 50k, 99.99
    if (/^\d+(?:[.,]\d+)?(?:k|m|b|%|s|ms|tps|rps)?$/i.test(token)) {
      result.push(token)
      continue
    }

    // Single character tokens (unless protected) are discarded
    if (token.length <= 1) {
      continue
    }

    // Filter out stopwords
    if (VI_STOPWORDS.has(token) || EN_STOPWORDS.has(token)) {
      continue
    }

    result.push(token)
  }

  return result
}
